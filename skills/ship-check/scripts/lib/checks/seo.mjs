import { blankComments, locate } from "../files.mjs";
import { collector } from "../items.mjs";

const METADATA =
  /export\s+(?:const\s+metadata\b|(?:async\s+)?function\s+generateMetadata\b|const\s+generateMetadata\b)/;

/** The root layout: `app/layout.tsx`, or the layout of a top-level group or `[locale]` segment. */
function rootLayout(ctx) {
  const re = new RegExp(`^${ctx.appDir}/(\\([^/]+\\)/|\\[[^/]+\\]/)?layout\\.[jt]sx?$`);
  return ctx.files.filter((f) => re.test(f.path)).sort((a, b) => a.path.length - b.path.length)[0];
}

/** @param {import("../project.mjs").Context} ctx */
export function checkSeo(ctx) {
  const { items, pass, warn } = collector("seo");
  if (!ctx.isNext || (!ctx.appDir && !ctx.pagesDir)) return items;
  const app = ctx.appDir;
  const anyPath = (re) => ctx.paths.find((p) => re.test(p.path));
  const code = (f) => (f ? blankComments(f.content) : "");

  const layout = app ? rootLayout(ctx) : undefined;
  const pagesShell = ctx.pagesDir
    ? ctx.files.filter((f) =>
        new RegExp(`^${ctx.pagesDir}/_(app|document)\\.[jt]sx?$`).test(f.path),
      )
    : [];
  const shellCode = layout ? code(layout) : pagesShell.map(code).join("\n");
  const shellFile = layout ?? pagesShell[0];

  // 1. Title and description.
  if (layout) {
    const hasMeta = METADATA.test(shellCode);
    const missing = [
      ["title", /\btitle\s*:/],
      ["description", /\bdescription\s*:/],
    ].filter(([, re]) => !hasMeta || !re.test(shellCode));
    // `export const metadata = buildMetadata()`: built by a helper this check can't follow.
    const literal = /export\s+const\s+metadata\b[^=]*=\s*\{/.test(shellCode);
    const viaHelper = hasMeta && !literal && !/function\s+generateMetadata\b/.test(shellCode);
    if (missing.length === 0) {
      pass("metadata", `Root metadata has a title and description (\`${layout.path}\`)`);
    } else if (viaHelper) {
      pass(
        "metadata",
        `Root metadata exported from \`${layout.path}\` (built by a helper; confirm title and description)`,
      );
    } else {
      warn(
        "metadata",
        hasMeta
          ? `Root metadata has no ${missing.map(([n]) => n).join(" or ")}`
          : "Root layout exports no `metadata` or `generateMetadata`",
        {
          file: layout.path,
          why: "Search results and shared links show the URL or 'Create Next App' instead of the product name and a description.",
          fix: 'Export `metadata` from the root layout: `export const metadata = { title: { default: "Name", template: "%s · Name" }, description: "..." }`.',
        },
      );
    }
  } else if (ctx.pagesDir) {
    const titled =
      /<title\b/.test(shellCode) ||
      ctx.hasDep(/^next-seo$/) ||
      ctx.sourceFiles.some(
        (f) => /from\s+["']next\/head["']/.test(f.content) && /<title\b/.test(f.content),
      );
    if (titled) pass("metadata", "Pages set a `<title>` via `next/head`");
    else {
      warn("metadata", "No `<title>` set via `next/head`", {
        why: "Search results and shared links show the URL instead of the product name.",
        fix: 'Set `<title>` and `<meta name="description">` with `next/head` on each page (or in `_app`).',
      });
    }
  }

  // 2. metadataBase (App Router only).
  if (app) {
    const base = ctx.sourceFiles.find((f) => /\bmetadataBase\s*:/.test(code(f)));
    if (base) pass("metadata-base", `\`metadataBase\` set (\`${base.path}\`)`);
    else {
      warn("metadata-base", "`metadataBase` is not set", {
        ...(layout ? { file: layout.path } : {}),
        why: "Open Graph and canonical URLs are resolved against it; without it they point to localhost or the preview URL, and shared links show no image.",
        fix: "Add `metadataBase: new URL(env.SITE_URL)` to the root metadata, with the production URL coming from an environment variable.",
      });
    }
  }

  // 3. robots and sitemap.
  const robots =
    (app && anyPath(new RegExp(`^${app}/robots\\.[jt]s$`))) || anyPath(/^public\/robots\.txt$/);
  if (robots) pass("robots", `robots rules present (\`${robots.path}\`)`);
  else {
    warn("robots", "No robots.txt", {
      why: "Crawlers get no guidance (and no sitemap link); preview or admin areas you meant to hide can be indexed.",
      fix: app
        ? `Add \`${app}/robots.ts\` returning \`{ rules: { userAgent: "*", allow: "/" }, sitemap: "https://<domain>/sitemap.xml" }\`.`
        : "Add `public/robots.txt`.",
    });
  }
  const sitemap =
    (app && anyPath(new RegExp(`^${app}/(.+/)?sitemap\\.(xml|[jt]s)$`))) ||
    anyPath(/^public\/sitemap[^/]*\.xml$/);
  if (sitemap) pass("sitemap", `Sitemap present (\`${sitemap.path}\`)`);
  else if (ctx.hasDep(/^next-sitemap$/)) pass("sitemap", "Sitemap generated by `next-sitemap`");
  else {
    warn("sitemap", "No sitemap", {
      why: "Search engines discover pages more slowly, and Google Search Console has nothing to submit.",
      fix: app
        ? `Add \`${app}/sitemap.ts\` listing the public URLs.`
        : "Generate `public/sitemap.xml` (e.g. with `next-sitemap`).",
    });
  }

  // 4. Favicon.
  const icon =
    (app &&
      anyPath(
        new RegExp(`^${app}/(favicon\\.ico|icon\\.[a-z]+|icon\\d*\\.[a-z]+|apple-icon\\.[a-z]+)$`),
      )) ||
    anyPath(/^public\/(favicon\.(ico|svg|png)|icon\.(svg|png))$/) ||
    (/\bicons\s*:/.test(shellCode) && shellFile ? { path: shellFile.path } : undefined);
  if (icon) pass("favicon", `Favicon present (\`${icon.path}\`)`);
  else {
    warn("favicon", "No favicon", {
      why: "Browser tabs, bookmarks and home-screen shortcuts show a blank or default icon: the first thing a client notices.",
      fix: app
        ? `Add \`${app}/icon.png\` (or \`favicon.ico\`); Next.js wires it up automatically.`
        : "Add `public/favicon.ico`.",
    });
  }

  // 5. Open Graph image.
  const ogFile = app && anyPath(new RegExp(`^${app}/(.+/)?(opengraph|twitter)-image\\.[a-z]+$`));
  const ogMeta = ctx.sourceFiles.find((f) => {
    const c = code(f);
    return /\bopenGraph\s*:/.test(c) && /\bimages\s*:/.test(c);
  });
  const og = ogFile || ogMeta;
  if (og) pass("og-image", `Open Graph image configured (\`${og.path}\`)`);
  else {
    warn("og-image", "No Open Graph image", {
      why: "Links shared on WhatsApp, LinkedIn, Slack or X show a bare URL instead of a preview card.",
      fix: app
        ? `Add \`${app}/opengraph-image.png\` (1200×630) or generate one with \`opengraph-image.tsx\`.`
        : "Add `og:image` meta tags with an absolute URL to a 1200×630 image.",
    });
  }

  // 6. <html lang>.
  const langFile = layout ?? pagesShell.find((f) => /\/_document\./.test(f.path));
  if (langFile || ctx.pagesDir) {
    const html = langFile ? /<html\b[^>]*>/i.exec(code(langFile)) : null;
    if (html && /\blang\s*=/.test(html[0])) pass("html-lang", "`<html>` has a `lang` attribute");
    else {
      warn("html-lang", "`<html>` has no `lang` attribute", {
        ...(langFile && html
          ? locate(langFile, html.index)
          : langFile
            ? { file: langFile.path }
            : {}),
        why: "Screen readers guess the language and browsers offer to translate the page; it is also an accessibility audit failure.",
        fix: layout
          ? 'Set it in the root layout: `<html lang="en">` (the site\'s language).'
          : 'Set it in `pages/_document.tsx`: `<Html lang="en">`.',
      });
    }
  }
  return items;
}
